#!/usr/bin/env python3
"""Read-only linked ROM inventory. Never writes engine/config/ROM inputs.

Usage: codex_rom_capacity.py ENGINE ELF ROM [--output FILE]
Occupancy comes from __rom_end, not padded image length. Sample accounting
matches generated bytes at linked labels; inactive assembly branches and
multiple labels at one address do not count twice. Requires an ELF32 ARM LE
build, generated sample bins and the matching linker map beside the ELF.
"""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import re
import struct

ROM_BASE = 0x08000000
ROM_LIMIT = 32 * 1024 * 1024


def sha(data):
    return hashlib.sha256(data).hexdigest()


class Elf:
    def __init__(self, data):
        self.data = data
        if len(data) < 52 or data[:7] != b'\x7fELF\x01\x01\x01':
            raise ValueError('expected ELF32 little-endian version 1')
        h = struct.unpack_from('<16sHHIIIIIHHHHHH', data)
        if h[2] != 40 or h[11] != 40 or not h[12]:
            raise ValueError('expected ARM ELF with section headers')
        self.sections = [struct.unpack('<IIIIIIIIII', self.read(h[6]+40*i, 40))
                         for i in range(h[12])]
        names = self.section_data(h[13])
        self.names = [self.string(names, s[0]) for s in self.sections]
        self.symbols = {}
        for section in self.sections:
            if section[1] != 2:
                continue
            if section[9] != 16 or section[5] % 16:
                raise ValueError('invalid symbol table')
            strings = self.section_data(section[6])
            for offset in range(section[4], section[4]+section[5], 16):
                name, address, size, info, _, index = struct.unpack('<IIIBBH', self.read(offset, 16))
                name = self.string(strings, name)
                if name:
                    self.symbols[name] = (address, size, info & 15, index)

    @staticmethod
    def string(data, offset):
        return data[offset:data.index(0, offset)].decode('utf-8')

    def read(self, offset, size):
        if offset < 0 or size < 0 or offset + size > len(self.data):
            raise ValueError('ELF range outside file')
        return self.data[offset:offset+size]

    def section_data(self, index):
        section = self.sections[index]
        return self.read(section[4], section[5])

    def at_symbol(self, name, size):
        address, _, _, index = self.symbols[name]
        section = self.sections[index]
        relative = address - section[3]
        if section[1] == 8 or relative < 0 or relative + size > section[5]:
            raise ValueError('symbol range outside file-backed section')
        return self.read(section[4]+relative, size)

    def occupancy(self):
        used = self.symbols['__rom_end'][0] - ROM_BASE
        if not 0 < used <= ROM_LIMIT:
            raise ValueError('linked image outside current 32 MiB contract')
        return {'linked_used_bytes': used, 'free_bytes': ROM_LIMIT-used}


def samples(engine, elf):
    labels, seen, rows = [], set(), []
    for line in (engine/'sound/direct_sound_data.inc').read_text().splitlines():
        match = re.match(r'^(DirectSoundWaveData_\w+|Cry_\w+)::', line)
        if match:
            labels.append(match[1])
        match = re.search(r'\.incbin "([^"]+)"', line)
        if not match:
            continue
        path = match[1]
        for label in labels:
            if label not in elf.symbols or elf.symbols[label][0] in seen:
                continue
            data = (engine/path).read_bytes()
            if elf.at_symbol(label, len(data)) != data:
                continue  # alternate inactive branch with same label
            seen.add(elf.symbols[label][0])
            category = 'cries' if '/cries/' in path else 'phonemes' if '/phonemes/' in path else 'instruments_other'
            rows.append({'label': label, 'path': path, 'category': category,
                         'bytes': len(data), 'sha256': sha(data)})
        labels = []
    totals = {}
    for category in ('cries', 'phonemes', 'instruments_other'):
        group = [row for row in rows if row['category'] == category]
        totals[category] = {'count': len(group), 'bytes': sum(r['bytes'] for r in group)}
    return {'totals': totals, 'blobs': rows}


def input_sections(map_text):
    """Only named single-line .rodata inputs, not output/LTO attribution."""
    rows = []
    for match in re.finditer(r'^ \.rodata\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+(\S+\.o)\s*$', map_text, re.M):
        address, size, name = match.groups()
        if int(address, 16) >= ROM_BASE:
            rows.append({'object': name, 'bytes': int(size, 16)})
    return sorted(rows, key=lambda r: (-r['bytes'], r['object']))


def forecast(layouts, other_categories, free_bytes):
    """Layouts are incremental scenario inputs, NOT approved map designs.

    List of {count,width,height}; cost is raw u16 block + 2x2 u16 border.
    Headers/events/scripts are separately budgeted by caller.
    """
    total = 0
    for row in layouts:
        count, width, height = (row[k] for k in ('count', 'width', 'height'))
        if any(type(n) is not int or n < 1 for n in (count, width, height)):
            raise ValueError('positive integer layout scenario required')
        if (width+15)*(height+14) > 10240:
            raise ValueError('layout exceeds current padded runtime buffer')
        total += count * (2*width*height+8)
    if any(type(n) is not int or n < 0 for n in other_categories.values()):
        raise ValueError('nonnegative integer category required')
    growth = total + sum(other_categories.values())
    return {'layout_bytes': total, 'growth_including_reserve_bytes': growth,
            'headroom_after_reserve_bytes': free_bytes-growth}


def inventory(engine, elf_path, rom_path):
    elf_data, rom = elf_path.read_bytes(), rom_path.read_bytes()
    elf = Elf(elf_data)
    used = elf.occupancy()['linked_used_bytes']
    if len(rom) < used:
        raise ValueError('ROM shorter than linked occupancy')
    sample_data = samples(engine, elf)
    songs = [name for name, (_, _, _, index) in elf.symbols.items()
             if name.startswith(('mus_', 'se_')) and index < len(elf.sections)]
    return {
        **elf.occupancy(), 'padded_file_bytes': len(rom),
        'rom_sha256': sha(rom), 'elf_sha256': sha(elf_data),
        'pokemon_config_sha256': sha((engine/'include/config/pokemon.h').read_bytes()),
        'sections': {name: s[5] for name, s in zip(elf.names, elf.sections)
                     if s[2] & 2 and ROM_BASE <= s[3] < ROM_BASE+ROM_LIMIT},
        'input_rodata': input_sections(elf_path.with_suffix('.map').read_text()),
        'songs_count': len(songs), 'song_names_sha256': sha('\n'.join(sorted(songs)).encode()),
        'samples': sample_data,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('engine', type=Path)
    parser.add_argument('elf', type=Path)
    parser.add_argument('rom', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    text = json.dumps(inventory(args.engine, args.elf, args.rom), indent=2)+'\n'
    if args.output:
        args.output.write_text(text)
    else:
        print(text, end='')


if __name__ == '__main__':
    main()
